import 'dart:async';

import 'package:firebase_core/firebase_core.dart';
import 'package:firebase_messaging/firebase_messaging.dart';
import 'package:flutter/material.dart';

import 'firebase_options.dart';
import 'models.dart';
import 'services/alarm_service.dart';
import 'services/device_service.dart';
import 'screens/history_screen.dart';
import 'screens/home_screen.dart';
import 'screens/login_screen.dart';
import 'screens/settings_screen.dart';
import 'services/alert_service.dart';
import 'services/session.dart';
import 'theme.dart';

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  // Settings generated by `flutterfire configure` (project gas-dectactor)
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  await Session.instance.load(); // remembered login from last time

  runApp(const GldApp());

  // Permission, push topic and token in the background, so the app opens instantly
  AlertService.instance.init();
}

class GldApp extends StatelessWidget {
  const GldApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'GLD',
      debugShowCheckedModeBanner: false,
      theme: buildTheme(Brightness.light),
      darkTheme: buildTheme(Brightness.dark),
      // Login screen until a demo user signs in (see data/user_dummy.dart)
      home: ListenableBuilder(
        listenable: Session.instance,
        builder: (context, _) => Session.instance.user == null
            ? const LoginScreen()
            : const HomeShell(),
      ),
    );
  }
}

class HomeShell extends StatefulWidget {
  const HomeShell({super.key});

  @override
  State<HomeShell> createState() => _HomeShellState();
}

class _HomeShellState extends State<HomeShell> {
  int _tab = 0;
  late final StreamSubscription<RemoteMessage> _openedFromPush;
  late final StreamSubscription<DeviceState> _alarmWatch;
  bool _wasLeak = false;

  @override
  void initState() {
    super.initState();
    // Tapping a gas notification always opens the live dashboard
    _openedFromPush =
        FirebaseMessaging.onMessageOpenedApp.listen((_) => setState(() => _tab = 0));

    // Siren when a leak starts while the app is open (also when the app opens during a leak)
    _alarmWatch = DeviceService.watchState().listen((s) {
      final leak = s.gas && s.isOnline(DateTime.now());
      if (leak && !_wasLeak) {
        AlarmService.instance.start();
        setState(() => _tab = 0); // show the red dashboard and the Stop button
      }
      if (!leak) AlarmService.instance.stop();
      _wasLeak = leak;
    }, onError: (_) {});
  }

  @override
  void dispose() {
    _openedFromPush.cancel();
    _alarmWatch.cancel();
    AlarmService.instance.stop();
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      body: IndexedStack(
        index: _tab,
        children: const [HomeScreen(), HistoryScreen(), SettingsScreen()],
      ),
      bottomNavigationBar: NavigationBar(
        selectedIndex: _tab,
        onDestinationSelected: (i) => setState(() => _tab = i),
        destinations: const [
          NavigationDestination(
            icon: Icon(Icons.home_outlined),
            selectedIcon: Icon(Icons.home_rounded),
            label: 'Home',
          ),
          NavigationDestination(
            icon: Icon(Icons.history_outlined),
            selectedIcon: Icon(Icons.history_rounded),
            label: 'History',
          ),
          NavigationDestination(
            icon: Icon(Icons.settings_outlined),
            selectedIcon: Icon(Icons.settings_rounded),
            label: 'Settings',
          ),
        ],
      ),
    );
  }
}
